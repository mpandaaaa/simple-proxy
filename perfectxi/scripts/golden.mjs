/**
 * Golden number tests.
 *
 * The Dixon-Coles constants and the strength curve were balanced by hand
 * over a long time. They are easy to break by accident and almost
 * impossible to notice breaking by eye, because a wrong league still looks
 * like a league. These are the numbers that say it is still the same game:
 *
 *   about 2.75 goals a game
 *   a champion somewhere around 90 points
 *   a replay of a seed producing exactly the season it produced before
 *
 * Run after any change to src/engine:  npm run golden
 */
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const engine = require(resolve(root, '.headless/engine/index.js'));

const {
  mulberry32,
  defaultConfig,
  newDraft,
  spin,
  place,
  slotsForPlayer,
  canPlay,
  squadAvg,
  chemBonus,
  simulateSeason,
  dcExpected,
  FORMATIONS,
} = engine;

const RUNS = 200;

let failures = 0;
function check(label, actual, low, high, fmt = (v) => v.toFixed(2)) {
  const ok = actual >= low && actual <= high;
  if (!ok) failures++;
  console.log(
    `  ${ok ? 'pass' : 'FAIL'}  ${label.padEnd(34)} ${fmt(actual).padStart(8)}` +
      `   expected ${fmt(low)} to ${fmt(high)}`,
  );
}

function draftXI(rnd) {
  let state = newDraft({ ...defaultConfig });
  let guard = 0;
  while (state.filled < state.total) {
    if (++guard > 500) throw new Error('draft could not be completed');
    const result = spin(state, rnd);
    if (!result) throw new Error('no clubs in the selected era');
    const pick = result.board.find((p) => canPlay(state, p));
    if (!pick) continue;
    state = place(state, pick, slotsForPlayer(state, pick)[0]);
  }
  return state;
}

console.log(`Golden numbers over ${RUNS} seasons\n`);

let goalsTotal = 0;
let championPts = 0;
let yourPts = 0;
let avgRating = 0;
let unbeaten = 0;

for (let seed = 1; seed <= RUNS; seed++) {
  const rnd = mulberry32(seed);
  const state = draftXI(rnd);
  const season = simulateSeason(
    state.squad,
    state.config.formation,
    chemBonus(state.squad),
    rnd,
  );

  // Goals per game across the whole division, not just your own fixtures:
  // every side in the table played 38, and each of those games has two
  // teams in it, so the league's goals are counted once per side.
  const leagueGoals = season.table.reduce((n, r) => n + r.gf, 0);
  goalsTotal += leagueGoals / (season.table.length * 38);

  championPts += season.table[0].pts;
  yourPts += season.pts;
  avgRating += squadAvg(state.squad);
  if (season.losses === 0) unbeaten++;
}

console.log('MATCH ENGINE');

// The balance point is the goals in an evenly matched game: two sides of
// equal strength, neutral formation, one at home. That is the number the
// constants were tuned around, and it rises gently with quality because
// better sides create more than they prevent. Measure this rather than the
// league's raw goals per game, which mixes in the filler teams' own Poisson
// season and answers a different question.
const even = [0.4, 0.5, 0.62, 0.75, 0.9].map((s) => {
  const e = dcExpected(s, s, true, FORMATIONS['4-4-2']);
  return e.lam + e.mu;
});
check('goals, even match at 0.40', even[0], 2.45, 2.65);
check('goals, even match at 0.62', even[2], 2.53, 2.73);
check('goals, even match at 0.90', even[4], 2.64, 2.84);
check('champion points', championPts / RUNS, 86, 96, (v) => v.toFixed(1));

// Locked as behaviour rather than as a design target: the nineteen filler
// clubs are generated by their own Poisson process, so this figure is not
// the same as the one above and is not meant to be.
check('league goals per game', (goalsTotal / RUNS) * 2, 2.2, 2.5);

console.log('\nDRAFT');
check('average squad rating', avgRating / RUNS, 78, 88, (v) => v.toFixed(1));
check('points for a random XI', yourPts / RUNS, 40, 80, (v) => v.toFixed(1));
check('unbeaten seasons', (unbeaten / RUNS) * 100, 0, 5, (v) => v.toFixed(1) + '%');

// A run is verified on the server by replaying it. If the same seed and the
// same picks can produce two different seasons then no run can ever be
// checked, and the leaderboard is only as honest as the client.
console.log('\nREPLAY');
function playSeed(seed) {
  const rnd = mulberry32(seed);
  const state = draftXI(rnd);
  const season = simulateSeason(
    state.squad,
    state.config.formation,
    chemBonus(state.squad),
    rnd,
  );
  return JSON.stringify({
    xi: state.squad.map((s) => s.player.n + '|' + s.player.club),
    pts: season.pts,
    gf: season.gf,
    ga: season.ga,
    pos: season.position,
    grade: season.grade,
    matches: season.matches.map((m) => m.gf + '-' + m.ga),
  });
}
let identical = true;
for (const seed of [1, 42, 1993, 20260901]) {
  if (playSeed(seed) !== playSeed(seed)) {
    identical = false;
    console.log(`  FAIL  seed ${seed} did not replay to the same season`);
  }
}
if (identical) console.log('  pass  every seed replays to the same season');
else failures++;

console.log(
  failures === 0
    ? '\nAll golden numbers hold.'
    : `\n${failures} golden number(s) moved. The tuned maths has changed.`,
);
process.exit(failures === 0 ? 0 : 1);
